import java.nio.file.*;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.*;
import java.io.IOException;

public class Main {
    static String run(String value) throws Exception {
        String expected = System.getenv("BADASS_ADMIN_PASSWORD");
        return expected != null && !expected.isEmpty() && expected.equals(value) ? "ADMIN" : "DENIED";
    }
    public static void main(String[] args) throws Exception {
        if (args.length != 1) throw new IllegalArgumentException("Expected one input");
        System.out.print(run(args[0]));
    }
}
