#define _POSIX_C_SOURCE 200809L
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>
#include <fcntl.h>
#include <unistd.h>
#include <sys/stat.h>

int main(int argc, char **argv) {
    if (argc != 2) return 2;
    const char *value = argv[1];
    if (strcmp(value, "/home") && strcmp(value, "/profile")) { puts("DENIED"); return 0; }
    printf("Location: %s", value);
    return 0;
}
